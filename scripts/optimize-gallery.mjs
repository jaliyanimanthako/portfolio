// Builds responsive versions of the gallery photos plus tiny blur placeholders.
//   npm run gallery:optimize   (needs `cwebp` — brew install webp)
// Reads public/gallery/*.webp (using a same-named .jpg/.png original when present for better quality),
// writes public/gallery/sized/<name>-<width>.webp and src/data/galleryImages.js.
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { tmpdir } from 'node:os';

const root = new URL('..', import.meta.url).pathname;
const src = join(root, 'public/gallery');
const out = join(src, 'sized');
const WIDTHS = [480, 960, 1600];

const size = (file) => {
  const info = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', file], { encoding: 'utf8' });
  return [Number(info.match(/pixelWidth: (\d+)/)[1]), Number(info.match(/pixelHeight: (\d+)/)[1])];
};
const cwebp = (input, output, width, quality) => execFileSync('cwebp', ['-quiet', '-mt', '-metadata', 'none', '-q', String(quality), '-resize', String(width), '0', input, '-o', output]);

mkdirSync(out, { recursive: true });
const manifest = {};
for (const file of readdirSync(src).filter((f) => f.endsWith('.webp')).sort()) {
  const name = basename(file, '.webp');
  const original = ['.jpg', '.jpeg', '.png'].map((ext) => join(src, name + ext)).find(existsSync);
  const input = original ?? join(src, file);
  const [w, h] = size(join(src, file));
  const widths = WIDTHS.filter((x) => x < w);
  if (widths.length < WIDTHS.length) widths.push(Math.min(w, WIDTHS[WIDTHS.length - 1]));
  for (const width of widths) cwebp(input, join(out, `${name}-${width}.webp`), width, 76);
  const tiny = join(tmpdir(), `${name}-blur.webp`);
  cwebp(input, tiny, 24, 40);
  manifest[file] = { width: w, height: h, widths, placeholder: `data:image/webp;base64,${readFileSync(tiny).toString('base64')}` };
  rmSync(tiny);
  console.log(`${file}: ${widths.join(', ')}`);
}
writeFileSync(join(root, 'src/data/galleryImages.js'),
  `// Generated by scripts/optimize-gallery.mjs — do not edit by hand.\nexport const galleryImages = ${JSON.stringify(manifest, null, 2)};\n`);
